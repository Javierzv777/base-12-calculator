//! Divisibility by a divisor of twelve, decided from the **last digit**.
//!
//! Since `12 = 2^2 * 3`, a dozenal numeral `n = 12 q + r` (with `r` its
//! last digit) is divisible by every `d` that divides twelve exactly when
//! `r` is. So for `d` in `{2, 3, 4, 6, 12}` the whole decision is a
//! one-digit decoder, the same pattern as `circuits::parity` -- instead of
//! the restoring division that `Dz::div_rem` would run over every digit.
//! (For `d = 12` the "last digit" rule says `r = 0`.)
//!
//! # Where the set of good last digits comes from
//!
//! The row "which digits are multiples of `d`" is **not typed in**. It is
//! synthesized by gates, once, with a throwaway `MvlGates` memoized in a
//! `OnceLock` -- the same pattern, and for the same reason, as
//! `lo_hi_table()` in `circuits::multiplier` (the table that once held
//! native `j * k` and was fixed in commit 18565f8):
//!
//! * repeatedly add `d` to a running digit with `half_adder`, twelve times,
//!   keeping every sum -- for `d | 12` that walk visits exactly the
//!   multiples of `d` below twelve (the subgroup of `Z12` generated by `d`);
//! * `row[j] = MAX_k lit(j, m_k)` marks which `j` were visited.
//!
//! For a `d` that does *not* divide twelve the same walk visits a larger
//! subgroup, which is **not** the set of multiples of `d` -- so the rows of
//! such `d` are never used; `SMALL_DIVISOR_TAGS` and the twelve check are
//! the only entry points, and callers decide eligibility with gates
//! (`dz_int::last_digit_divisible`).

use crate::backends::MvlGates;
use crate::circuits::adder::half_adder;
use crate::circuits::depth::GateNet;
use crate::digit::{Digit, RADIX};
use crate::traits::DozGates;
use std::sync::OnceLock;

/// The single-digit divisors of twelve other than one. Circuit-structure
/// constants (which `lit` branches the decoder has), like `EVEN_TAGS` in
/// `circuits::parity` -- not a computation on any digit's tag. Twelve
/// itself is two digits (`10`) and is recognised by the caller.
pub const SMALL_DIVISOR_TAGS: [u8; 4] = [2, 3, 4, 6];

type Row = [Digit; RADIX as usize];

/// `rows[c] = (Digit c, flags)` where `flags[j] = MAX` iff `j` is a
/// multiple of `c` (reached by repeated addition of `c`).
fn rows() -> &'static Vec<(Digit, Row)> {
    static ROWS: OnceLock<Vec<(Digit, Row)>> = OnceLock::new();
    ROWS.get_or_init(|| {
        let init_gates = MvlGates::new();
        let mut table = Vec::with_capacity(RADIX as usize);
        let mut c: u8 = 0;
        while c < RADIX {
            let step = Digit::new(c).expect("c is in 0..RADIX");
            // The walk 0, c, c+c, ... : twelve running sums.
            let mut walk = Vec::with_capacity(RADIX as usize);
            let mut acc = Digit::ZERO;
            let mut k: u8 = 0;
            while k < RADIX {
                walk.push(acc);
                acc = half_adder(&init_gates, acc, step).0;
                k += 1;
            }
            // flags[j] = OR_k [walk_k == j], as an MVL boolean.
            let mut flags: Row = [Digit::ZERO; RADIX as usize];
            let mut j: u8 = 0;
            while j < RADIX {
                let mut seen = Digit::ZERO;
                for &m in walk.iter() {
                    seen = init_gates.max(seen, init_gates.lit(j, m));
                }
                flags[j as usize] = seen;
                j += 1;
            }
            table.push((step, flags));
            c += 1;
        }
        table
    })
}

/// The synthesized row for divisor digit `c`: `row[j]` is `Digit::MAX` if
/// `j` is a multiple of `c`, `Digit::ZERO` otherwise. Only meaningful when
/// `c` divides twelve (see the module docs); `c = Digit::ZERO` stands for
/// twelve itself and yields the row of multiples of zero, i.e. `{0}`.
///
/// The lookup compares symbols for equality (a table lookup, the same
/// category as `flag_to_bool`), never arithmetic on a tag.
pub fn divisor_row(c: Digit) -> [Digit; RADIX as usize] {
    rows()
        .iter()
        .find(|(key, _)| key == &c)
        .map(|(_, row)| row.to_owned())
        .expect("the table has an entry for every digit")
}

/// MVL-boolean "the last digit `x` is a multiple of the divisor whose row
/// is `row`": `MAX_j MIN( lit(j, x), row[j] )`. Twelve `lit`, twelve `min`
/// and eleven `max`: 35 invocations for every divisor, and a depth of 13.
pub fn last_digit_divisible_net<N: GateNet>(net: &N, row: &[Digit; RADIX as usize], x: N::S) -> N::S {
    let mut out = net.lift(Digit::ZERO);
    let mut j: u8 = 0;
    while j < RADIX {
        let branch = net.min(net.lit(j, x), net.lift(row[j as usize]));
        out = if j == 0 { branch } else { net.max(out, branch) };
        j += 1;
    }
    out
}

/// `Values` instantiation of [`last_digit_divisible_net`], for the divisor
/// digit `c` (`Digit::ZERO` for twelve).
pub fn last_digit_divisible<G: DozGates>(g: &G, c: Digit, x: Digit) -> Digit {
    last_digit_divisible_net(&crate::circuits::depth::Values(g), &divisor_row(c), x)
}
